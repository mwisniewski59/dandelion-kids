'use strict';
// Emits ONE self-contained, idempotent SQL script for the plan.
//
// Safe to run twice: customers are matched by email then phone digits;
// a drop-off is skipped when the tenant already has a drop-off with the
// same dropped_at for the same customer (email / phone digits / id).
// The script refuses to run if the tenant is missing or migration 0004 has
// not been applied. It only INSERTs (plus total_drops recount and gap-fill
// of missing email/phone on matched customers); it never deletes.

const { ACTOR } = require('./plan');

const lit = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const ts = v => lit(v);   // temp table columns are typed; literals cast implicitly

function chunk(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}

function buildSql(plan, { tenantId, transaction = true } = {}) {
  if (!tenantId || !/^[0-9a-f-]{36}$/i.test(tenantId)) throw new Error('buildSql: valid tenantId (uuid) required');
  const T = lit(tenantId);
  const B = lit(plan.batchId);
  const L = [];
  L.push(`-- Sellers' Sheet (Form Responses 5) import`);
  L.push(`-- batch ${plan.batchId}; cutoff ${plan.cutoff}; ${plan.dropoffs.length} drop-off rows; ${plan.customers.length} customers`);
  L.push(`-- Generated by tools/import-sellers-sheet. CONTAINS PERSONAL DATA when generated`);
  L.push(`-- from a real export: do not commit, delete after the import.`);
  if (transaction) L.push('begin;');
  L.push('');
  L.push(`do $$ begin
  if not exists (select 1 from public.tenants where id = ${T}) then
    raise exception 'tenant ${tenantId} not found in this database';
  end if;
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'dropoffs' and column_name = 'picked_up_at') then
    raise exception 'apply supabase/migrations/0004_awaiting_pickup.sql before importing';
  end if;
  if not exists (select 1 from pg_constraint where conname = 'dropoffs_stage_check'
                 and pg_get_constraintdef(oid) like '%awaiting_pickup%') then
    raise exception 'dropoffs_stage_check does not allow awaiting_pickup; apply migration 0004 first';
  end if;
end $$;`);
  L.push('');
  L.push(`create temp table _imp_c (
  ckey text primary key, name text not null, email text, phone text, phone_digits text,
  customer_id uuid, is_new boolean not null default false
) on commit drop;`);
  for (const part of chunk(plan.customers, 200)) {
    L.push('insert into _imp_c (ckey, name, email, phone, phone_digits) values');
    L.push(part.map(c => `  (${lit(c.key)}, ${lit(c.name)}, ${lit(c.email)}, ${lit(c.phone)}, ${lit(c.phone_digits)})`).join(',\n') + ';');
  }
  L.push('');
  L.push(`create temp table _imp_d (
  row_no int primary key, ckey text not null, drop_type text not null, bag_description text,
  donate_all boolean not null, consented boolean not null, dropped_at timestamptz not null,
  stage text not null, tagged_at timestamptz, priced_at timestamptz,
  venmo_amount numeric(10,2), credit_amount numeric(10,2), offer_sent_at timestamptz,
  customer_responded_at timestamptz, payment_choice text, leftover_choice text,
  resolved_at timestamptz, paid_at timestamptz, picked_up_at timestamptz, notes text,
  dropoff_id uuid
) on commit drop;`);
  for (const part of chunk(plan.dropoffs, 200)) {
    L.push('insert into _imp_d (row_no, ckey, drop_type, bag_description, donate_all, consented, dropped_at, stage, tagged_at, priced_at, venmo_amount, credit_amount, offer_sent_at, customer_responded_at, payment_choice, leftover_choice, resolved_at, paid_at, picked_up_at, notes) values');
    L.push(part.map(d => '  (' + [
      d.row_no, lit(d.customer_key), lit(d.drop_type), lit(d.bag_description), lit(d.donate_all), lit(d.consented),
      ts(d.dropped_at), lit(d.stage), ts(d.tagged_at), ts(d.priced_at), lit(d.venmo_amount), lit(d.credit_amount),
      ts(d.offer_sent_at), ts(d.customer_responded_at), lit(d.payment_choice), lit(d.leftover_choice),
      ts(d.resolved_at), ts(d.paid_at), ts(d.picked_up_at), lit(d.notes),
    ].join(', ') + ')').join(',\n') + ';');
  }
  L.push('');
  L.push(`-- 1. Match existing customers in this tenant: email first, then last 10 phone digits.
update _imp_c i set customer_id = (
  select c.id from public.customers c
  where c.tenant_id = ${T} and i.email is not null and lower(c.email) = i.email
  order by c.created_at limit 1);
update _imp_c i set customer_id = (
  select c.id from public.customers c
  where c.tenant_id = ${T} and i.phone_digits is not null
    and right(regexp_replace(coalesce(c.phone, ''), '\\D', '', 'g'), 10) = i.phone_digits
  order by c.created_at limit 1)
where customer_id is null;
update _imp_c set customer_id = gen_random_uuid(), is_new = true where customer_id is null;

-- 2. Create new customers; fill gaps (never overwrite) on matched ones.
insert into public.customers (id, tenant_id, name, email, phone)
select customer_id, ${T}, name, email, phone from _imp_c where is_new;
update public.customers c
   set email = coalesce(c.email, i.email), phone = coalesce(c.phone, i.phone)
  from _imp_c i
 where c.id = i.customer_id and not i.is_new and (c.email is null or c.phone is null)
   and (i.email is not null or i.phone is not null);

-- 3. Mark rows that already exist (same tenant + dropped_at + customer).
alter table _imp_d add column already_present boolean not null default false;
update _imp_d d set already_present = true
  from _imp_c i
 where i.ckey = d.ckey and exists (
   select 1 from public.dropoffs x join public.customers xc on xc.id = x.customer_id
   where x.tenant_id = ${T} and x.dropped_at = d.dropped_at
     and (x.customer_id = i.customer_id
          or (i.email is not null and lower(xc.email) = i.email)
          or (i.email is null and i.phone_digits is not null
              and right(regexp_replace(coalesce(xc.phone, ''), '\\D', '', 'g'), 10) = i.phone_digits)));

-- 4. Insert drop-offs.
update _imp_d set dropoff_id = gen_random_uuid() where not already_present;
insert into public.dropoffs (
  id, tenant_id, customer_id, drop_type, bag_description, donate_all, consented, dropped_at, stage,
  tagged_at, tagged_by, priced_at, priced_by, venmo_amount, credit_amount, offer_sent_at,
  customer_responded_at, payment_choice, leftover_choice, resolved_at, paid_at, paid_by,
  picked_up_at, picked_up_by, notes)
select d.dropoff_id, ${T}, i.customer_id, d.drop_type, d.bag_description, d.donate_all, d.consented, d.dropped_at, d.stage,
  d.tagged_at, case when d.tagged_at is not null then '${ACTOR}' end,
  d.priced_at, case when d.priced_at is not null then '${ACTOR}' end,
  d.venmo_amount, d.credit_amount, d.offer_sent_at,
  d.customer_responded_at, d.payment_choice, d.leftover_choice, d.resolved_at, d.paid_at,
  case when d.paid_at is not null then '${ACTOR}' end,
  d.picked_up_at, case when d.picked_up_at is not null then '${ACTOR}' end,
  d.notes
from _imp_d d join _imp_c i on i.ckey = d.ckey
where not d.already_present
order by d.row_no;

-- 5. Audit trail (also the handle for rollback: details->>'batch').
insert into public.activity_log (tenant_id, dropoff_id, actor, action, details)
select ${T}, d.dropoff_id, '${ACTOR}', 'imported',
       jsonb_build_object('batch', ${B}, 'source', 'Sellers Sheet 2026 / Form Responses 5', 'sheet_row', d.row_no)
from _imp_d d where not d.already_present;

-- 6. Keep customers.total_drops equal to their drop-off count.
update public.customers c set total_drops = (select count(*) from public.dropoffs x where x.customer_id = c.id)
 where c.id in (select customer_id from _imp_c);

-- 7. Result summary.
select jsonb_build_object(
  'batch', ${B},
  'customers_created', (select count(*) from _imp_c where is_new),
  'customers_matched', (select count(*) from _imp_c where not is_new),
  'dropoffs_inserted', (select count(*) from _imp_d where not already_present),
  'dropoffs_skipped_already_present', (select count(*) from _imp_d where already_present),
  'inserted_by_stage', (select coalesce(jsonb_object_agg(stage, n), '{}'::jsonb) from (select stage, count(*) n from _imp_d where not already_present group by stage) s),
  'inserted_venmo_total', (select coalesce(sum(venmo_amount), 0) from _imp_d where not already_present),
  'inserted_credit_total', (select coalesce(sum(credit_amount), 0) from _imp_d where not already_present)
) as import_result;`);
  if (transaction) L.push('commit;');
  return L.join('\n') + '\n';
}

function buildRollbackSql(plan, { tenantId }) {
  const T = lit(tenantId);
  const B = lit(plan.batchId);
  return `-- Roll back Sellers' Sheet import batch ${plan.batchId}.
-- Deletes ONLY drop-offs created by this batch (via activity_log), then any
-- customer that was created by it and now has no drop-offs left.
begin;
create temp table _rb on commit drop as
  select dropoff_id, created_at from public.activity_log
  where tenant_id = ${T} and action = 'imported' and details->>'batch' = ${B};
create temp table _rb_c on commit drop as
  select distinct customer_id from public.dropoffs where id in (select dropoff_id from _rb);
delete from public.dropoffs where id in (select dropoff_id from _rb);   -- cascades activity_log rows
delete from public.customers c
 where c.id in (select customer_id from _rb_c)
   and not exists (select 1 from public.dropoffs x where x.customer_id = c.id)
   and c.created_at >= (select min(created_at) from _rb) - interval '1 hour';
update public.customers c set total_drops = (select count(*) from public.dropoffs x where x.customer_id = c.id)
 where c.id in (select customer_id from _rb_c);
commit;
`;
}

function buildJson(plan, { tenantId }) {
  return {
    batch_id: plan.batchId,
    tenant_id: tenantId || null,
    cutoff: plan.cutoff,
    customers: plan.customers.map(c => ({ key: c.key, name: c.name, email: c.email, phone: c.phone, phone_digits: c.phone_digits })),
    dropoffs: plan.dropoffs.map(d => { const { flags, ...rest } = d; return { ...rest, flags }; }),
    skipped: plan.skipped,
  };
}

module.exports = { buildSql, buildRollbackSql, buildJson, lit };
